"""
Data export manager: Multi-format export (CSV, HDF5, WAV).
"""

import os
import json
import numpy as np
import pandas as pd
import soundfile as sf
import h5py
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional
import warnings

warnings.filterwarnings('ignore')


class ExportManager:
    """Manages export of recorded data to multiple formats."""
    
    def __init__(self, base_output_dir: str = None):
        """
        Initialize export manager.
        
        Args:
            base_output_dir: Base directory for all recordings
        """
        if base_output_dir is None:
            home = Path.home()
            base_output_dir = home / "EEG_Recordings"
        
        self.base_output_dir = Path(base_output_dir)
        self.base_output_dir.mkdir(parents=True, exist_ok=True)
    
    def create_session_directory(self, session_name: Optional[str] = None) -> Path:
        """
        Create session output directory.
        
        Args:
            session_name: Custom session name (autogenerated if None)
            
        Returns:
            Path to session directory
        """
        if session_name is None:
            timestamp = datetime.now().strftime("%Y-%m-%d_%H%M%S")
        else:
            timestamp = session_name
        
        session_dir = self.base_output_dir / timestamp
        session_dir.mkdir(parents=True, exist_ok=True)
        
        return session_dir
    
    def export_session(self, session_dir: Path, recording_data: Dict,
                      session_metadata: Dict, eeg_fs: int = 250,
                      audio_fs: int = 16000, export_formats: List[str] = None):
        """
        Export all recorded data to multiple formats.
        
        Args:
            session_dir: Session output directory
            recording_data: Dict with 'eeg', 'audio', 'resist' data
            session_metadata: Session metadata (device, time, etc.)
            eeg_fs: EEG sampling rate
            audio_fs: Audio sampling rate
            export_formats: List of formats to export ('csv', 'hdf5', 'wav')
                           If None, exports all formats
        """
        if export_formats is None:
            export_formats = ['csv', 'hdf5', 'wav']
        
        session_name = session_dir.name
        
        # Save metadata
        self._save_metadata(session_dir, session_metadata)
        
        # Extract data
        eeg_data = recording_data.get('eeg', [])
        audio_data = recording_data.get('audio', [])
        resist_data = recording_data.get('resist', [])
        
        # Export to requested formats
        if 'csv' in export_formats:
            self._export_to_csv(
                session_dir, session_name, eeg_data, audio_data, resist_data,
                eeg_fs, audio_fs
            )
        
        if 'hdf5' in export_formats:
            self._export_to_hdf5(
                session_dir, session_name, eeg_data, audio_data, resist_data,
                session_metadata, eeg_fs, audio_fs
            )
        
        if 'wav' in export_formats:
            self._export_audio_to_wav(
                session_dir, session_name, audio_data, audio_fs
            )
    
    def _save_metadata(self, session_dir: Path, metadata: Dict):
        """Save session metadata to JSON."""
        metadata_file = session_dir / "session_metadata.json"
        
        # Convert non-serializable objects to strings
        metadata_clean = {}
        for key, value in metadata.items():
            if isinstance(value, (str, int, float, bool, list, dict, type(None))):
                metadata_clean[key] = value
            else:
                metadata_clean[key] = str(value)
        
        with open(metadata_file, 'w') as f:
            json.dump(metadata_clean, f, indent=2)
    
    def _export_to_csv(self, session_dir: Path, session_name: str,
                       eeg_data: List, audio_data: List, resist_data: List,
                       eeg_fs: int, audio_fs: int):
        """Export data to separate CSV files."""
        
        # Export EEG
        if eeg_data:
            eeg_df = self._create_eeg_dataframe(eeg_data, eeg_fs)
            eeg_file = session_dir / f"{session_name}_eeg.csv"
            eeg_df.to_csv(eeg_file, index=False)
            print(f"Exported EEG: {eeg_file}")
        
        # Export Audio
        if audio_data:
            audio_df = self._create_audio_dataframe(audio_data, audio_fs)
            audio_file = session_dir / f"{session_name}_audio.csv"
            audio_df.to_csv(audio_file, index=False)
            print(f"Exported Audio: {audio_file}")
        
        # Export Resistance
        if resist_data:
            resist_df = self._create_resist_dataframe(resist_data)
            resist_file = session_dir / f"{session_name}_resistance.csv"
            resist_df.to_csv(resist_file, index=False)
            print(f"Exported Resistance: {resist_file}")
    
    def _create_eeg_dataframe(self, eeg_data: List, sampling_rate: int) -> pd.DataFrame:
        """Create EEG DataFrame with raw and filtered data."""
        data_dict = {
            'timestamp': [],
            'Ch1': [],
            'Ch2': [],
            'Ch3': [],
            'Ch4': []
        }
        
        for entry in eeg_data:
            data_dict['timestamp'].append(entry['timestamp'])
            for i, ch_val in enumerate(entry['channels']):
                data_dict[f'Ch{i+1}'].append(ch_val)
        
        df = pd.DataFrame(data_dict)
        
        # Add filtered versions (basic FIR filter simulation)
        for ch in range(1, 5):
            col_name = f"Ch{ch}"
            if len(df) > 1:
                # Simple moving average filter as placeholder
                window = int(sampling_rate / 10)  # ~100ms window
                if window < 2:
                    window = 2
                df[f"{col_name}_filtered"] = df[col_name].rolling(
                    window=window, center=True
                ).mean()
            else:
                df[f"{col_name}_filtered"] = df[col_name]
        
        return df
    
    def _create_audio_dataframe(self, audio_data: List, sampling_rate: int) -> pd.DataFrame:
        """Create Audio DataFrame."""
        data_dict = {
            'timestamp': [],
            'audio_sample': []
        }
        
        for entry in audio_data:
            data_dict['timestamp'].append(entry['timestamp'])
            data_dict['audio_sample'].append(entry['sample'])
        
        return pd.DataFrame(data_dict)
    
    def _create_resist_dataframe(self, resist_data: List) -> pd.DataFrame:
        """Create Resistance DataFrame."""
        data_dict = {
            'timestamp': [],
            'Ch1_ohms': [],
            'Ch2_ohms': [],
            'Ch3_ohms': [],
            'Ch4_ohms': []
        }
        
        for entry in resist_data:
            data_dict['timestamp'].append(entry['timestamp'])
            for i, ch_val in enumerate(entry['channels']):
                data_dict[f'Ch{i+1}_ohms'].append(ch_val)
        
        return pd.DataFrame(data_dict)
    
    def _export_to_hdf5(self, session_dir: Path, session_name: str,
                        eeg_data: List, audio_data: List, resist_data: List,
                        metadata: Dict, eeg_fs: int, audio_fs: int):
        """Export data to HDF5 format."""
        hdf5_file = session_dir / f"{session_name}.h5"
        
        try:
            with h5py.File(hdf5_file, 'w') as f:
                # Metadata
                metadata_group = f.create_group('metadata')
                metadata_group.attrs['eeg_sampling_rate'] = eeg_fs
                metadata_group.attrs['audio_sampling_rate'] = audio_fs
                metadata_group.attrs['export_time'] = datetime.now().isoformat()
                for key, value in metadata.items():
                    try:
                        metadata_group.attrs[str(key)] = str(value)
                    except:
                        pass
                
                # EEG data
                if eeg_data:
                    eeg_group = f.create_group('eeg')
                    timestamps = np.array([e['timestamp'] for e in eeg_data])
                    channels = np.array([e['channels'] for e in eeg_data])
                    
                    eeg_group.create_dataset('timestamps', data=timestamps)
                    eeg_group.create_dataset('raw', data=channels, compression='gzip')
                    eeg_group.attrs['num_channels'] = 4
                    eeg_group.attrs['num_samples'] = len(channels)
                
                # Audio data
                if audio_data:
                    audio_group = f.create_group('audio')
                    timestamps = np.array([a['timestamp'] for a in audio_data])
                    samples = np.array([a['sample'] for a in audio_data])
                    
                    audio_group.create_dataset('timestamps', data=timestamps)
                    audio_group.create_dataset('samples', data=samples, compression='gzip')
                    audio_group.attrs['num_samples'] = len(samples)
                
                # Resistance data
                if resist_data:
                    resist_group = f.create_group('resistance')
                    timestamps = np.array([r['timestamp'] for r in resist_data])
                    channels = np.array([r['channels'] for r in resist_data])
                    
                    resist_group.create_dataset('timestamps', data=timestamps)
                    resist_group.create_dataset('channels', data=channels, compression='gzip')
                    resist_group.attrs['num_channels'] = 4
                    resist_group.attrs['num_samples'] = len(channels)
            
            print(f"Exported HDF5: {hdf5_file}")
            
        except Exception as e:
            print(f"Error exporting HDF5: {e}")
    
    def _export_audio_to_wav(self, session_dir: Path, session_name: str,
                            audio_data: List, sampling_rate: int):
        """Export audio to WAV file."""
        if not audio_data:
            return
        
        wav_file = session_dir / f"{session_name}_audio.wav"
        
        try:
            # Extract audio samples
            samples = np.array([a['sample'] for a in audio_data], dtype=np.float32)
            
            # Normalize if needed
            if len(samples) > 0:
                max_val = np.abs(samples).max()
                if max_val > 1.0:
                    samples = samples / max_val * 0.95
            
            # Write to WAV file
            sf.write(wav_file, samples, sampling_rate)
            print(f"Exported Audio WAV: {wav_file}")
            
        except Exception as e:
            print(f"Error exporting WAV: {e}")
